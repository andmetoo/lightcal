#[cfg(test)]
mod local_event_text_tests {
    use super::*;

    #[test]
    fn every_language_has_the_local_event_text() {
        for locale in LocaleCode::ALL {
            let text = local_event_text(locale);
            for value in [
                text.new_event,
                text.title,
                text.save,
                text.cancel,
                text.err_title,
                text.delete_question,
                text.panel_unavailable_title,
                text.back,
            ] {
                assert!(!value.is_empty(), "{locale:?}");
            }
            for template in [text.err_too_many, text.over_count, text.panel_over_count] {
                assert!(template.contains("{max}"), "{locale:?}: {template}");
            }
            assert!(text.over_count.contains("{n}") && text.panel_over_count.contains("{n}"));
        }
    }

    #[test]
    fn counts_are_grouped_per_language() {
        let t = "{n}/{max}";
        assert_eq!(
            local_count_text(LocaleCode::En, t, 2140, 2000),
            "2,140/2,000"
        );
        assert_eq!(
            local_count_text(LocaleCode::De, t, 2140, 2000),
            "2.140/2.000"
        );
        assert_eq!(local_count_text(LocaleCode::Ru, t, 2140, 2000), "2140/2000");
        assert_eq!(
            local_count_text(LocaleCode::Fr, t, 999, 2000),
            "999/2\u{202f}000"
        );
    }
}

