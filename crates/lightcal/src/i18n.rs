/// Russian and Ukrainian plural form: `one` for 1, 21, 31…; `few` for 2-4, 22-24…;
/// `many` for 0, 5-20, 25-30….
pub(crate) fn slavic_plural<'a>(
    count: usize,
    one: &'a str,
    few: &'a str,
    many: &'a str,
) -> &'a str {
    let rem100 = count % 100;
    let rem10 = count % 10;
    if (11..=14).contains(&rem100) {
        many
    } else if rem10 == 1 {
        one
    } else if (2..=4).contains(&rem10) {
        few
    } else {
        many
    }
}

