#[cfg(test)]
mod local_settings_text_tests {
    use super::*;

    #[test]
    fn every_language_has_the_local_settings_text() {
        for locale in LocaleCode::ALL {
            let text = local_settings_text(locale);
            assert!(text.skipped.contains("{events}"), "{locale:?}");
            assert!(text.over_count.contains("{events}") && text.over_count.contains("{max}"));
            for template in [
                text.retrying,
                text.unreadable,
                text.cannot_save,
                text.no_lock,
            ] {
                assert!(template.contains("{error}"), "{locale:?}: {template}");
            }
            for value in [text.ok, text.start_over, text.quit_title, text.keep_open] {
                assert!(!value.is_empty(), "{locale:?}");
            }
        }
    }
}
